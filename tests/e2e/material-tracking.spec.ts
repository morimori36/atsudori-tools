import { test,expect } from '@playwright/test';
import { inventoryFixture,inventoryTraining } from '../helpers/inventory';
import { chooseScreen } from '../helpers/navigation';
import { CATALOG_STORAGE_KEY,STORAGE_KEY,MATERIAL_INVENTORY_BACKUP_KEY } from '../../src/storage/local';
import { TRAINING_STORAGE_KEY } from '../../src/storage/training-settings';
for(const width of [1280,390])test(`retired material migration and legacy import protection at ${width}px`,async({page})=>{
 const {m,c}=inventoryFixture();
 m.materialDefinition!.excludedResourceIds=['retired-token'];
 c.resourceInventory={paper:5,'retired-token':91,'unknown-backup':8};
 const raw=JSON.stringify(c);
 await page.setViewportSize({width,height:844});await page.goto('./');
 await page.evaluate(({m,raw,settings,keys})=>{
  localStorage.setItem(keys[0]!,JSON.stringify(m));localStorage.setItem(keys[1]!,raw);localStorage.setItem(keys[2]!,JSON.stringify(settings));
 },{m,raw,settings:inventoryTraining,keys:[CATALOG_STORAGE_KEY,STORAGE_KEY,TRAINING_STORAGE_KEY]});
 await page.reload();await chooseScreen(page,page.locator('nav [data-tab=inventory]'));
 await expect(page.locator('[data-inventory-input="paper"]')).toHaveValue('5');
 await expect(page.locator('[data-inventory-unsupported="retired-token"]')).toHaveCount(0);
 expect(await page.evaluate(k=>localStorage.getItem(k),STORAGE_KEY)).toBe(raw);
 await page.locator('[data-inventory-input="paper"]').fill('7');
 await expect.poll(()=>page.evaluate(k=>JSON.parse(localStorage.getItem(k)!).resourceInventory.paper,STORAGE_KEY)).toBe(7);
 expect(await page.evaluate(k=>localStorage.getItem(k),MATERIAL_INVENTORY_BACKUP_KEY)).toBe(raw);
 expect(await page.evaluate(k=>JSON.parse(localStorage.getItem(k)!).resourceInventory,STORAGE_KEY)).toEqual({paper:7,'unknown-backup':8});
 await page.reload();await chooseScreen(page,page.locator('nav [data-tab=inventory]'));
 await expect(page.locator('[data-inventory-input="paper"]')).toHaveValue('7');
 await chooseScreen(page,page.locator('nav [data-tab=exchange]'));
 const legacy=structuredClone(m);delete legacy.materialDefinition!.trackingVersion;delete legacy.materialDefinition!.excludedResourceIds;
 await page.locator('#catalog-import').setInputFiles({name:'legacy.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(legacy))});
 await expect(page.getByRole('alert').filter({hasText:'追跡範囲'})).toContainText('追跡範囲');
 expect(await page.evaluate(k=>JSON.parse(localStorage.getItem(k)!).materialDefinition.trackingVersion,CATALOG_STORAGE_KEY)).toBe(1);
});
