import {test, expect} from '@playwright/test';
import {budgetPlanFixture} from '../helpers/budget-plan';
import {CATALOG_STORAGE_KEY, STORAGE_KEY} from '../../src/storage/local';
import {chooseScreen} from '../helpers/navigation';

for (const width of [320, 390, 1280]) test(`integrated plan shares settings, protects failed saves and reloads at ${width}`, async ({page}) => {
  const {master, collection} = budgetPlanFixture();
  await page.setViewportSize({width, height: 900});
  await page.goto('./#exchange');
  const file = (value: unknown) => ({name: 'fictional.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(value))});
  await page.locator('#catalog-import').setInputFiles(file(master));
  await expect(page.getByText('マスタをImportしました', {exact: true})).toBeVisible();
  await page.locator('#import-file').setInputFiles(file(collection));
  await expect(page.getByText('所持データをImportしました', {exact: true})).toBeVisible();
  const saved = () => page.evaluate(k => JSON.parse(localStorage.getItem(k)!), STORAGE_KEY);
  const catalog = await page.evaluate(k => localStorage.getItem(k), CATALOG_STORAGE_KEY);
  const before = await saved();
  await chooseScreen(page, page.locator('nav [data-tab=seal-budget]'));
  await expect(page.locator('[data-plan-income]')).toHaveText('557.14');
  await expect(page.locator('[data-plan-exchange]')).toHaveText('257.14');
  await expect(page.locator('[data-plan-balance]')).toHaveText('+300');
  expect(await saved()).toEqual(before);
  await page.locator('[name=paid][value="1"]').check();
  await expect(page.locator('[data-seal-income]')).toHaveText('240');
  await expect(page.locator('[data-plan-gacha-expense]')).toHaveText('240');
  await expect(page.locator('[data-plan-balance]')).toHaveText('+60');
  await expect(page.locator('[data-plan-paid-balance]')).toHaveText('-68.57');
  await expect(page.locator('[data-plan-status]')).toHaveText('有償スター不足');
  await page.locator('[name=passPlan][value=premium]').check();
  await page.locator('[name=pass]').check();
  await expect(page.locator('[data-plan-income]')).toHaveText('814.29');
  await expect(page.locator('[data-plan-balance]')).toHaveText('+317.14');
  await expect(page.locator('[data-seal-income]')).toHaveText('698.33');
  await expect(page.locator('[data-plan-status]')).toHaveText('平均収支の範囲で継続可能な目安');
  const successful = await saved();
  expect(successful.starBudgetScenario).toEqual({...before.starBudgetScenario, passPlan: 'premium'});
  expect(successful.members).toEqual(before.members);
  expect(successful.snaps).toEqual(before.snaps);
  await chooseScreen(page, page.locator('nav [data-tab=star-budget]'));
  await expect(page.locator('[name="scenario.passPlan"][value=premium]')).toBeChecked();
  await expect(page.locator('th[aria-current=true]')).toHaveText('Premium（計画で選択中）');
  await page.locator('[name="scenario.passPlan"][value=lite]').check();
  await page.locator('[name="selected-crystal-luck"]').uncheck();
  await chooseScreen(page, page.locator('nav [data-tab=seal-budget]'));
  await expect(page.locator('[name=passPlan][value=lite]')).toBeChecked();
  await expect(page.locator('[data-plan-exchange]')).toHaveText('0');
  await expect(page.locator('[data-plan-income]')).toHaveText('642.86');
  await expect(page.locator('[data-seal-income]')).toHaveText('386.67');
  const bytes = await page.evaluate(k => localStorage.getItem(k), STORAGE_KEY);
  await page.evaluate(() => {
    const original = Storage.prototype.setItem;
    Storage.prototype.setItem = function() {
      Storage.prototype.setItem = original;
      throw new Error('quota');
    };
  });
  await page.locator('[name=passPlan][value=none]').check();
  await expect(page.locator('[data-seal-message]')).toContainText('未保存');
  await expect(page.locator('.seal-stale')).toBeVisible();
  await expect(page.locator('[data-plan-income]')).toHaveText('642.86');
  expect(await page.evaluate(k => localStorage.getItem(k), STORAGE_KEY)).toBe(bytes);
  await page.locator('[name=cm]').check();
  await expect(page.locator('.seal-stale')).toHaveCount(0);
  await expect(page.locator('[data-plan-income]')).toHaveText('557.14');
  await expect(page.locator('[data-seal-income]')).toHaveText('2,880');
  expect((await saved()).starBudgetScenario.passPlan).toBe('none');
  await page.reload();
  await expect(page.locator('[data-plan-income]')).toHaveText('557.14');
  await expect(page.locator('[name=passPlan][value=none]')).toBeChecked();
  expect(await page.evaluate(k => localStorage.getItem(k), CATALOG_STORAGE_KEY)).toBe(catalog);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  for (const label of await page.locator('.seal-plan-controls label').all()) expect((await label.boundingBox())!.height).toBeGreaterThanOrEqual(44);
  await page.screenshot({path: `test-results/budget-plan-${width}.png`, fullPage: true});
});

test('integrated receipt exposes missing definitions and known-only estimates', async ({page}) => {
  const {master, collection, definition} = budgetPlanFixture();
  delete definition.planBenefits;
  delete master.starBudgetDefinition!.currencyBreakdown;
  collection.sealBudgetScenario!.cm = true;
  collection.sealBudgetScenario!.paid = 1;
  await page.goto('./#seal-budget');
  await page.evaluate(({master, collection, ck, sk}) => {
    localStorage.setItem(ck, JSON.stringify(master)); localStorage.setItem(sk, JSON.stringify(collection));
  }, {master, collection, ck: CATALOG_STORAGE_KEY, sk: STORAGE_KEY});
  await page.reload();
  await expect(page.locator('[data-seal-income]')).toHaveText('2,640');
  await expect(page.locator('[data-plan-income]')).toHaveText('557.14');
  await expect(page.locator('.seal-notes')).toContainText('未確認');
  await expect(page.locator('[data-plan-status]')).not.toHaveText('平均収支の範囲で継続可能な目安');
});
